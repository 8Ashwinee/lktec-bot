"""The ``lockfiles`` module's command: ``commit`` the lock files regenerated for a Dependabot
pull request onto its branch.

The lock files are regenerated by a job that runs the pull request's code and holds no secret;
this command runs in a second job, with the App credentials, and treats what it is handed as
untrusted: only known lock file names, only plain relative paths, files that really lie inside
the directory it was given. What changed is decided here, by comparing every file with the
pull request head's own copy read through the API, not by trusting a list from the first job.
The commit itself is the ``commit`` verb, signed by GitHub.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from enum import StrEnum
from pathlib import Path

from lktec_bot.application.gate import Gate, VerbOutcome, VerbRequest, VerbResult
from lktec_bot.application.modules.automerge.classify import DEPENDABOT_LOGIN
from lktec_bot.application.modules.lockfiles.ecosystems import ecosystem_of, within
from lktec_bot.application.modules.lockfiles.options import LockfilesOptions
from lktec_bot.domain.paths import repo_path_problem
from lktec_bot.domain.permissions import Target, Verb
from lktec_bot.domain.policy import Policy
from lktec_bot.ports.github_api import GitHubApi, PullRequest
from lktec_bot.text import escape_markdown

MODULE = "lockfiles"
READ_PERMISSIONS = {"contents": "read", "pull_requests": "read"}
MANIFEST = "manifest.txt"
FILES_DIR = "files"
COMMENT_MARKER = "lockfiles"
MAX_FILE_BYTES = 10 * 1024 * 1024
# Lock file paths end up in a commit message and a comment, and in ``--add path=file``.
_SAFE_PATH = re.compile(r"^[A-Za-z0-9._/@+ -]+$")


class Decision(StrEnum):
    """The outcome of ``commit`` for one pull request."""

    COMMITTED = "committed"
    UNCHANGED = "unchanged"
    SKIPPED = "skipped"
    DENIED = "denied"
    ERROR = "error"


@dataclass(frozen=True, slots=True)
class CommitOutcome:
    number: int
    decision: Decision
    reason: str
    url: str | None = None
    warnings: tuple[str, ...] = ()

    @property
    def exit_code(self) -> int:
        return {Decision.DENIED: 3, Decision.ERROR: 1}.get(self.decision, 0)

    @property
    def result(self) -> str:
        """The coarse ``result`` output: ``ok``, ``denied`` or ``error``."""
        return {Decision.DENIED: "denied", Decision.ERROR: "error"}.get(self.decision, "ok")

    def to_markdown(self, repository: str) -> str:
        head = f"**{self.decision.value.upper()}** `lockfiles commit` #{self.number}"
        text = f"{head} on `{repository}`: {escape_markdown(self.reason)}"
        if self.url:
            text += f"\n\n<{self.url}>"
        for warning in self.warnings:
            text += f"\n\nWarning: {escape_markdown(warning)}"
        return text + "\n"


class HandoverError(ValueError):
    """What the regenerating job handed over cannot be trusted or read."""


@dataclass(frozen=True, slots=True)
class _Assessment:
    options: LockfilesOptions
    pull_request: PullRequest
    skip: str | None = None
    # Selected lock file -> its text at the pull request head (``None``: not there yet).
    heads: dict[str, str | None] = field(default_factory=dict)
    ignored: tuple[str, ...] = ()


def read_manifest(changed_dir: Path) -> list[str]:
    """The repository paths the first job reports as changed lock files.

    Every one must be a plain relative path whose file name is a known lock file name; if any
    is not, the whole handover is refused (nothing is committed).
    """
    try:
        text = (changed_dir / MANIFEST).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise HandoverError(f"cannot read {MANIFEST} in {changed_dir}: {exc}") from None
    paths: list[str] = []
    problems: list[str] = []
    for raw in text.splitlines():
        path = raw.strip()
        if not path or path in paths:
            continue
        problem = repo_path_problem(path)
        if problem is None and not _SAFE_PATH.match(path):
            problem = "the path has characters outside letters, digits and . _ / @ + - space"
        if problem is None and ecosystem_of(path) is None:
            problem = "not the name of a known lock file"
        if problem is not None:
            problems.append(f"{path!r}: {problem}")
        paths.append(path)
    if problems:
        raise HandoverError("refusing the handover: " + "; ".join(problems))
    return paths


def local_file(changed_dir: Path, path: str) -> Path:
    """The handed-over copy of ``path``: a regular file inside ``<changed_dir>/files``."""
    root = (changed_dir / FILES_DIR).resolve()
    candidate = changed_dir / FILES_DIR / path
    try:
        resolved = candidate.resolve(strict=True)
    except OSError:
        raise HandoverError(
            f"{MANIFEST} lists {path!r} but {FILES_DIR}/{path} is missing"
        ) from None
    if candidate.is_symlink() or not resolved.is_relative_to(root) or not resolved.is_file():
        raise HandoverError(f"{FILES_DIR}/{path} is not a plain file inside {FILES_DIR}/")
    if resolved.stat().st_size > MAX_FILE_BYTES:
        raise HandoverError(
            f"{FILES_DIR}/{path} is larger than {MAX_FILE_BYTES // (1024 * 1024)} MiB"
        )
    return resolved


class Lockfiles:
    """Commits regenerated lock files of one repository through a :class:`Gate`."""

    def __init__(self, gate: Gate, owner: str, repo: str) -> None:
        self._gate = gate
        self._owner = owner
        self._repo = repo

    def commit(self, number: int, changed_dir: Path, head_sha: str | None = None) -> CommitOutcome:
        """Commit the lock files in ``changed_dir`` that differ from pull request ``number``.

        ``head_sha`` is the head the files were regenerated for; a pull request that has moved
        on is skipped (its new head triggers a run of its own).
        """
        try:
            manifest = read_manifest(changed_dir)
            local = {path: local_file(changed_dir, path) for path in manifest}
        except HandoverError as exc:
            return CommitOutcome(number, Decision.ERROR, str(exc))

        read = self._gate.read(
            self._owner,
            self._repo,
            MODULE,
            READ_PERMISSIONS,
            lambda api, policy: self._assess(api, policy, number, manifest, head_sha),
        )
        warnings = read.warnings
        if read.failure is not None or read.value is None:
            failure = read.failure or VerbResult(VerbOutcome.ERROR, "nothing was read")
            return _failed(number, failure, warnings)
        assessment = read.value
        pull_request = assessment.pull_request
        if assessment.skip is not None:
            return CommitOutcome(
                number, Decision.SKIPPED, assessment.skip, pull_request.html_url, warnings
            )

        try:
            changed = [
                path
                for path, head in assessment.heads.items()
                if head is None or local[path].read_bytes() != head.encode("utf-8")
            ]
        except OSError as exc:
            return CommitOutcome(number, Decision.ERROR, f"cannot read a lock file: {exc}")
        if not changed:
            reason = "nothing to commit: the lock files already match the pull request head"
            if assessment.ignored:
                reason += f" (left out by the options: {', '.join(assessment.ignored)})"
            return CommitOutcome(
                number, Decision.UNCHANGED, reason, pull_request.html_url, warnings
            )
        return self._commit(number, assessment, changed, local, warnings)

    def _assess(
        self,
        api: GitHubApi,
        policy: Policy,
        number: int,
        manifest: list[str],
        head_sha: str | None,
    ) -> _Assessment:
        options = LockfilesOptions.model_validate(policy.modules[MODULE].options)
        pull_request = api.get_pull_request(self._owner, self._repo, number)
        skip = self._skip_reason(pull_request, head_sha)
        if skip is not None:
            return _Assessment(options, pull_request, skip=skip)
        selected: list[str] = []
        ignored: list[str] = []
        for path in manifest:
            wrong_ecosystem = bool(options.ecosystems) and (
                ecosystem_of(path) not in options.ecosystems
            )
            outside = bool(options.paths) and not any(within(path, s) for s in options.paths)
            (ignored if wrong_ecosystem or outside else selected).append(path)
        heads = {
            path: api.get_file_content(self._owner, self._repo, path, ref=pull_request.head_sha)
            for path in selected
        }
        return _Assessment(options, pull_request, heads=heads, ignored=tuple(ignored))

    def _skip_reason(self, pull_request: PullRequest, head_sha: str | None) -> str | None:
        if not pull_request.open:
            return f"pull request is {pull_request.state}, not open"
        if pull_request.draft:
            return "pull request is a draft"
        if pull_request.author_login != DEPENDABOT_LOGIN:
            return f"not opened by {DEPENDABOT_LOGIN}"
        if pull_request.head_repo.lower() != f"{self._owner}/{self._repo}".lower():
            return "the pull request branch lives in another repository"
        if not pull_request.head_ref:
            return "the pull request has no head branch"
        if head_sha is not None and pull_request.head_sha != head_sha:
            return (
                f"the pull request moved on from {head_sha[:12]} to "
                f"{pull_request.head_sha[:12]}; the run for the new head regenerates"
            )
        return None

    def _commit(
        self,
        number: int,
        assessment: _Assessment,
        changed: list[str],
        local: dict[str, Path],
        warnings: tuple[str, ...],
    ) -> CommitOutcome:
        pull_request = assessment.pull_request
        body = "Regenerated by lktec-bot:\n" + "".join(f"- {path}\n" for path in changed)
        result = self._gate.run(
            VerbRequest(
                self._owner,
                self._repo,
                MODULE,
                Verb.COMMIT,
                args={
                    "branch": pull_request.head_ref,
                    "message": assessment.options.headline(number),
                    "body": body,
                    "add": [f"{path}={local[path]}" for path in changed],
                    "expected_head": pull_request.head_sha,
                },
            )
        )
        if not result.ok:
            return _failed(number, result, warnings, "commit")
        outcome_warnings = (*warnings, *result.warnings)
        note = self._comment(number, changed, result.url)
        if note is not None:
            outcome_warnings = (*outcome_warnings, note)
        return CommitOutcome(
            number,
            Decision.COMMITTED,
            f"{result.message}: {', '.join(changed)}",
            result.url,
            outcome_warnings,
        )

    def _comment(self, number: int, changed: list[str], url: str | None) -> str | None:
        """Tell the pull request what happened; a failure is a warning, never the outcome."""
        files = ", ".join(f"`{path}`" for path in changed)
        link = f" ([commit]({url}))" if url else ""
        text = f"lktec-bot refreshed the lock files of this pull request: {files}{link}."
        result = self._gate.run(
            VerbRequest(
                self._owner,
                self._repo,
                MODULE,
                Verb.COMMENT,
                target=Target.PULL_REQUEST,
                args={
                    "number": number,
                    "body": text,
                    "marker": COMMENT_MARKER,
                },
            )
        )
        return (
            None
            if result.ok
            else f"the lock files were committed but the comment failed: {result.message}"
        )


def _failed(
    number: int, result: VerbResult, warnings: tuple[str, ...], step: str = ""
) -> CommitOutcome:
    decision = Decision.DENIED if result.outcome is VerbOutcome.DENIED else Decision.ERROR
    reason = f"{step}: {result.message}" if step else result.message
    return CommitOutcome(number, decision, reason, result.url, (*warnings, *result.warnings))
